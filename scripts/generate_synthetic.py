"""Generate the SYNTHETIC internal systems of a pharmacy chain (AGENTS.md §4.2).

  python scripts/generate_synthetic.py --seed 42                              # scored data
  python scripts/generate_synthetic.py --seed 7 --out data/tuning/seed7       # tuning data for B

Seeded from REAL regulator data in data/sample/regulator/ (run fetch_regulator.py and
scrape_npra.py first). Everything written here is synthetic and labelled so.

Writes (raw-table contract, AGENTS.md §7.4)
  <out>/inventory/stock.csv        stock_id, outlet_id, product_name, reg_no, batch, qty_on_hand, snapshot_date
  <out>/inventory/transfers.csv    transfer_id, leg, outlet_id, counterparty_outlet_id, product_name, reg_no, batch, qty, transfer_date
  <out>/pos/sales.csv              sale_id, outlet_id, sku, product_name, batch, qty, sold_at, loyalty_id
  <out>/supplier/deliveries.json   delivery_id, supplier_name, supplier_licence_no, outlet_id, supplier_product_name, reg_no, batch, qty, delivered_on
  <out>/recalls_used.json          the real NPRA recalls the data was built around (ready-made recall_alert inputs)
  <truth>                          answer key for scripts/evaluate.py. Agents never read it.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
import re
import sys
from collections import defaultdict
from datetime import date, datetime, timedelta
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
REG_DIR = ROOT / "data" / "sample" / "regulator"
DEFAULT_OUT = ROOT / "data" / "sample"
DEFAULT_TRUTH = ROOT / "data" / "ground_truth" / "exposures.json"

SNAPSHOT = date(2026, 10, 22)  # the day the chain's systems were "exported"
RECALLS_SINCE = "2026-01-01"  # recent enough that sales before and after the recall fit the window
SYNTHETIC_NOTE = "SYNTHETIC data generated by scripts/generate_synthetic.py; not real stock, sales or customers."

# Conflicts that should leave an exposure for pharmacist review rather than auto-confirm.
REVIEW_CONFLICTS = {"batch_typo", "one_sided_transfer", "delivered_not_in_inventory"}

UNLICENSED_SUPPLIER = "Medilink Trading Enterprise"  # synthetic; not on the licensed lists


def norm(v: str | None) -> str:
    return re.sub(r"[^A-Z0-9]", "", str(v or "").upper())


class Gen:
    def __init__(self, seed: int, outlets: int, records: int) -> None:
        self.rng = random.Random(seed)
        self.seed = seed
        self.outlets = [f"OUT-{i:02d}" for i in range(1, outlets + 1)]
        self.target_sales = records
        self.ids: dict[str, int] = defaultdict(int)
        self.stock: list[dict] = []
        self.transfers: list[dict] = []
        self.sales: list[dict] = []
        self.deliveries: list[dict] = []
        # (recall_id, outlet_id, batch_norm) -> {"conflicts": set, "evidence": list}
        self.truth: dict[tuple, dict] = {}
        self.decoys: list[dict] = []
        self.unassigned: list[dict] = []
        # Every injected conflict type appears at least once, whatever the seed.
        self.forced = ["delivered_not_in_inventory", "sale_from_zero_stock", "missing_reg_no",
                       "one_sided_transfer", "batch_typo", "unlicensed_supplier"]
        self.rng.shuffle(self.forced)

    # ---------- small helpers ----------

    def nid(self, prefix: str) -> str:
        self.ids[prefix] += 1
        return f"{prefix}-{self.ids[prefix]:06d}"

    def loyalty(self, outlet: str) -> str | None:
        if self.rng.random() < 0.3:
            return None  # walk-in, no loyalty card
        n = self.rng.randrange(25)
        return "LOY-" + hashlib.sha1(f"{self.seed}|{outlet}|{n}".encode()).hexdigest()[:10]

    def day(self, start: date, end: date) -> date:
        return start + timedelta(days=self.rng.randrange(max(1, (end - start).days + 1)))

    def fake_batch(self, like: str, avoid: set[str]) -> str:
        """A batch with the same shape as `like` but a different value (decoys, clean products)."""
        for _ in range(100):
            b = "".join(
                str(self.rng.randrange(10)) if c.isdigit()
                else self.rng.choice("ABCDEFGHJKLMNPRSTUVWXYZ") if c.isalpha() else c
                for c in like
            )
            if norm(b) not in avoid:
                return b
        raise RuntimeError("could not make a distinct batch")

    # ---------- per-system spellings (the fragmentation) ----------

    def pos_name(self, name: str) -> str:
        n = re.sub(r"\s*\(.*?\)", "", name).strip()
        swaps = [("Tablets", "Tab"), ("Tablet", "Tab"), ("Capsules", "Cap"), ("Capsule", "Cap"),
                 ("Injection", "Inj"), ("Syrup", "Sirap"), ("Cream", "Krim")]
        for a, b in swaps:
            if a.lower() in n.lower() and self.rng.random() < 0.7:
                n = re.sub(a, b, n, flags=re.I)
        return n.lower() if self.rng.random() < 0.5 else n.upper()

    def supplier_name(self, name: str) -> str:
        return f"{name.upper()} ({self.rng.choice(['BOX 30S', 'BTL', 'PACK 10X10', 'UNIT'])})"

    @staticmethod
    def pos_batch(b: str) -> str:
        return b.lower()

    def supplier_batch(self, b: str) -> str:
        if "-" in b or len(b) < 5:
            return b
        cut = len(b) // 2
        return f"{b[:cut]}-{b[cut:]}"

    def typo(self, b: str) -> str:
        subs = {"0": "o", "1": "l", "5": "s", "8": "b"}
        idx = [i for i, c in enumerate(b) if c in subs]
        if idx:
            i = self.rng.choice(idx)
            return b[:i] + subs[b[i]] + b[i + 1:]
        return b[:-1]  # dropped last character

    # ---------- building ----------

    def build(self, recalls: list[dict], clean: list[dict], suppliers: list[dict]) -> None:
        licensed = suppliers
        products = []
        # Two NPRA notices can cover the same product (same reg_no) with overlapping batch lists,
        # e.g. Glumet XR 750mg: one notice lists 5031724, another lists 16 batches including it.
        # A stocked batch is affected by EVERY chosen notice that lists it, and decoys must avoid
        # all of them.
        self.by_reg: dict[str, list[dict]] = defaultdict(list)
        for r in recalls:
            self.by_reg[r["reg_no"]].append({**r, "norm_batches": {norm(b) for b in r["batches"]}})
        for r in recalls:
            affected = r["batches"][:2]
            avoid = set().union(*(x["norm_batches"] for x in self.by_reg[r["reg_no"]]))
            decoys = [self.fake_batch(affected[0], avoid) for _ in range(self.rng.choice([1, 2]))]
            products.append({**r, "kind": "recalled", "affected": affected, "decoys": decoys,
                             "sku": f"SKU-{self.rng.randrange(10000, 99999)}"})
        for p in clean:
            b = self.fake_batch(self.rng.choice(["2410235", "B2405117", "24A0913"]), set())
            products.append({**p, "kind": "clean", "affected": [], "decoys": [b],
                             "sku": f"SKU-{self.rng.randrange(10000, 99999)}", "recall_id": None})

        sales_per_lot = max(2, self.target_sales // max(1, sum(3 for _ in products) * 2))
        unassigned_done = False
        for p in products:
            for outlet in sorted(self.rng.sample(self.outlets, self.rng.randint(2, min(5, len(self.outlets))))):
                lots = [(b, True) for b in p["affected"]] + [(b, False) for b in p["decoys"]]
                self.rng.shuffle(lots)
                for batch, is_affected in lots[: self.rng.randint(1, len(lots))]:
                    self.lot(p, outlet, batch, is_affected, sales_per_lot, licensed)
            if p["kind"] == "recalled" and not unassigned_done:
                self.unassigned_delivery(p, licensed)
                unassigned_done = True
        self.background_transfers(products)

    def lot(self, p: dict, outlet: str, batch: str, is_affected: bool, n_sales: int, licensed: list[dict]) -> None:
        rng = self.rng
        recall_date = date.fromisoformat(p["recall_date"]) if p.get("recall_date") else None
        conflicts: set[str] = {"batch_format", "name_variant"}
        evidence: list[dict] = []
        start = (recall_date - timedelta(days=60)) if recall_date else SNAPSHOT - timedelta(days=180)

        force = self.forced.pop() if is_affected and self.forced else None

        def roll(name: str, prob: float) -> bool:
            hit = is_affected and (name == force or rng.random() < prob)
            if hit:
                conflicts.add(name)
            return hit

        not_in_inventory = roll("delivered_not_in_inventory", 0.10)
        zero_stock = not not_in_inventory and roll("sale_from_zero_stock", 0.15)
        missing_reg = roll("missing_reg_no", 0.25)
        one_sided = roll("one_sided_transfer", 0.15)
        typo_sale = roll("batch_typo", 0.10)
        unlicensed = roll("unlicensed_supplier", 0.10)

        # supplier delivery
        if unlicensed:
            sup = {"company": UNLICENSED_SUPPLIER, "license_no": None}
        else:
            sup = rng.choice(licensed)
        delivered = self.day(start, start + timedelta(days=10))
        received = rng.randint(20, 60)
        d_id = self.nid("DLV")
        self.deliveries.append({
            "delivery_id": d_id, "supplier_name": sup["company"], "supplier_licence_no": sup["license_no"],
            "outlet_id": outlet, "supplier_product_name": self.supplier_name(p["product_name"]),
            "reg_no": p["reg_no"] if rng.random() < 0.7 else None, "batch": self.supplier_batch(batch),
            "qty": received, "delivered_on": delivered.isoformat(),
        })
        evidence.append({"source": "supplier", "record_id": d_id})

        # sales
        sold_total = 0
        sales_rows = []
        for i in range(rng.randint(max(1, n_sales // 2), n_sales + 2)):
            when = datetime.combine(self.day(delivered, SNAPSHOT), datetime.min.time()) + timedelta(
                hours=rng.randint(9, 21), minutes=rng.randrange(60))
            qty = rng.randint(1, 3)
            s_id = self.nid("SAL")
            row = {"sale_id": s_id, "outlet_id": outlet, "sku": p["sku"], "product_name": self.pos_name(p["product_name"]),
                   "batch": self.pos_batch(batch), "qty": qty, "sold_at": when.isoformat(sep=" "),
                   "loyalty_id": self.loyalty(outlet)}
            sales_rows.append(row)
            sold_total += qty
        if zero_stock and recall_date and not any(r["sold_at"][:10] >= recall_date.isoformat() for r in sales_rows):
            sales_rows[-1]["sold_at"] = f"{(recall_date + timedelta(days=3)).isoformat()} 15:20:00"
        if typo_sale:
            sales_rows[0]["batch"] = self.typo(batch).lower()
        self.sales.extend(sales_rows)
        evidence += [{"source": "pos", "record_id": r["sale_id"]} for r in sales_rows]

        # inventory stock snapshot
        on_hand = 0
        if not not_in_inventory:
            on_hand = 0 if zero_stock else max(0, received - sold_total - rng.randint(0, 5))
            st_id = self.nid("STK")
            self.stock.append({
                "stock_id": st_id, "outlet_id": outlet, "product_name": p["product_name"],
                "reg_no": None if missing_reg else p["reg_no"], "batch": batch.upper(),
                "qty_on_hand": on_hand, "snapshot_date": SNAPSHOT.isoformat(),
            })
            evidence.append({"source": "inventory", "record_id": st_id})

        # one-sided transfer: the "out" leg exists, the receiving outlet never booked it
        if one_sided:
            other = rng.choice([o for o in self.outlets if o != outlet])
            t_id = self.nid("TRF")
            self.transfers.append({
                "transfer_id": t_id, "leg": "out", "outlet_id": outlet, "counterparty_outlet_id": other,
                "product_name": p["product_name"], "reg_no": p["reg_no"], "batch": batch.upper(),
                "qty": rng.randint(2, 6), "transfer_date": self.day(delivered, SNAPSHOT).isoformat(),
            })
            evidence.append({"source": "inventory", "record_id": f"{t_id}:out"})

        if p["kind"] != "recalled":
            return
        affecting = [r for r in self.by_reg[p["reg_no"]] if norm(batch) in r["norm_batches"]]
        if not affecting:
            self.decoys += [{"outlet_id": outlet, "reg_no": p["reg_no"], "batch_norm": norm(batch),
                             "source": e["source"], "record_id": e["record_id"], "reason": "non_affected_batch"}
                            for e in evidence]
            return

        for r in affecting:  # one answer per notice that lists this batch, each with its own recall date
            r_date = r["recall_date"]
            sold_after = [s for s in sales_rows if s["sold_at"][:10] >= r_date]
            r_conflicts = (conflicts - {"sale_after_recall"}) | ({"sale_after_recall"} if sold_after else set())
            self.truth[(r["recall_id"], outlet, norm(batch))] = {
                "recall_id": r["recall_id"], "outlet_id": outlet, "reg_no": p["reg_no"], "batch_norm": norm(batch),
                "on_hand_qty": on_hand,
                "sold_after_date_qty": sum(s["qty"] for s in sold_after),
                "distinct_customers": len({s["loyalty_id"] for s in sold_after if s["loyalty_id"]}),
                "expected_status": "needs_review" if r_conflicts & REVIEW_CONFLICTS else "confirmed",
                "conflicts": sorted(r_conflicts),
                "evidence": evidence,
            }

    def unassigned_delivery(self, p: dict, licensed: list[dict]) -> None:
        sup = self.rng.choice(licensed)
        d_id = self.nid("DLV")
        batch = p["affected"][0]
        self.deliveries.append({
            "delivery_id": d_id, "supplier_name": sup["company"], "supplier_licence_no": sup["license_no"],
            "outlet_id": None, "supplier_product_name": self.supplier_name(p["product_name"]),
            "reg_no": p["reg_no"], "batch": self.supplier_batch(batch), "qty": self.rng.randint(10, 30),
            "delivered_on": self.day(SNAPSHOT - timedelta(days=30), SNAPSHOT).isoformat(),
        })
        self.unassigned.append({"recall_id": p["recall_id"], "reg_no": p["reg_no"], "batch_norm": norm(batch),
                                "source": "supplier", "record_id": d_id, "expected_status": "needs_review"})

    def background_transfers(self, products: list[dict]) -> None:
        """Ordinary two-leg transfers of clean stock: noise that must not raise a conflict."""
        clean = [s for s in self.stock if s["reg_no"]]
        for s in self.rng.sample(clean, min(len(clean), 6)):
            other = self.rng.choice([o for o in self.outlets if o != s["outlet_id"]])
            t_id, qty = self.nid("TRF"), self.rng.randint(1, 4)
            when = self.day(SNAPSHOT - timedelta(days=60), SNAPSHOT).isoformat()
            for leg, here, there in (("out", s["outlet_id"], other), ("in", other, s["outlet_id"])):
                self.transfers.append({
                    "transfer_id": t_id, "leg": leg, "outlet_id": here, "counterparty_outlet_id": there,
                    "product_name": s["product_name"], "reg_no": s["reg_no"], "batch": s["batch"],
                    "qty": qty, "transfer_date": when,
                })


# ---------- inputs ----------


def load_inputs(rng: random.Random, n_recalls: int, n_clean: int) -> tuple[list[dict], list[dict], list[dict]]:
    con = duckdb.connect()
    recalls = con.execute(
        f"""SELECT recall_id, recall_date, product_name, reg_no, batches, degree, level
            FROM read_csv('{(REG_DIR / 'npra_recalls.csv').as_posix()}', all_varchar=true)
            WHERE batches IS NOT NULL AND all_batches = 'False' AND recall_date >= ?
            ORDER BY recall_id""",
        [RECALLS_SINCE],
    ).fetchall()
    cols = ["recall_id", "recall_date", "product_name", "reg_no", "batches", "degree", "level"]
    recalls = [dict(zip(cols, r)) for r in recalls]
    for r in recalls:
        r["batches"] = r["batches"].split("|")
    if len(recalls) < n_recalls:
        raise SystemExit(f"only {len(recalls)} usable NPRA recalls since {RECALLS_SINCE}; run scrape_npra.py")
    recalls = rng.sample(recalls, n_recalls)

    clean = con.execute(
        f"""SELECT reg_no, product AS product_name
            FROM '{(REG_DIR / 'pharmaceutical_products.parquet').as_posix()}'
            WHERE status = 'PRODUCT APPROVED' AND description IN ('PRESCRIPTION', 'NON PRESCRIPTION')
            ORDER BY reg_no""",
    ).fetchall()
    clean = [{"reg_no": r[0], "product_name": r[1].strip()} for r in rng.sample(clean, n_clean)]

    suppliers = con.execute(
        f"""SELECT company, license_no FROM '{(REG_DIR / 'pharmaceutical_importers.parquet').as_posix()}'
            ORDER BY license_no""",
    ).fetchall()
    suppliers = [{"company": c, "license_no": l} for c, l in rng.sample(suppliers, 6)]
    return recalls, clean, suppliers


# ---------- output ----------


def write_csv(path: Path, rows: list[dict], cols: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--outlets", type=int, default=8)
    ap.add_argument("--records", type=int, default=500, help="approximate number of POS sale lines")
    ap.add_argument("--recalls", type=int, default=6, help="real NPRA recalls to build exposures around")
    ap.add_argument("--clean", type=int, default=14, help="unaffected products mixed in")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--truth", type=Path, default=None,
                    help="answer-key path (default: data/ground_truth/exposures.json for data/sample, else <out>/ground_truth/)")
    args = ap.parse_args(argv)

    out = args.out if args.out.is_absolute() else ROOT / args.out
    truth_path = args.truth or (DEFAULT_TRUTH if out.resolve() == DEFAULT_OUT.resolve() else out / "ground_truth" / "exposures.json")

    g = Gen(args.seed, args.outlets, args.records)
    recalls, clean, suppliers = load_inputs(g.rng, args.recalls, args.clean)
    g.build(recalls, clean, suppliers)

    write_csv(out / "inventory" / "stock.csv", g.stock,
              ["stock_id", "outlet_id", "product_name", "reg_no", "batch", "qty_on_hand", "snapshot_date"])
    write_csv(out / "inventory" / "transfers.csv", g.transfers,
              ["transfer_id", "leg", "outlet_id", "counterparty_outlet_id", "product_name", "reg_no", "batch", "qty", "transfer_date"])
    write_csv(out / "pos" / "sales.csv", g.sales,
              ["sale_id", "outlet_id", "sku", "product_name", "batch", "qty", "sold_at", "loyalty_id"])
    (out / "supplier").mkdir(parents=True, exist_ok=True)
    (out / "supplier" / "deliveries.json").write_text(json.dumps(g.deliveries, indent=1) + "\n", encoding="utf-8")
    (out / "recalls_used.json").write_text(json.dumps(
        [{"recall_id": r["recall_id"], "product_name": r["product_name"], "reg_no": r["reg_no"],
          "batches": r["batches"], "date": r["recall_date"], "degree_level": r["degree"] or r["level"]} for r in recalls],
        indent=2) + "\n", encoding="utf-8")

    truth = {
        "note": SYNTHETIC_NOTE,
        "seed": args.seed,
        "snapshot_date": SNAPSHOT.isoformat(),
        "review_conflicts": sorted(REVIEW_CONFLICTS),
        "exposures": sorted(g.truth.values(), key=lambda e: (e["recall_id"], e["outlet_id"], e["batch_norm"])),
        "unassigned": g.unassigned,
        "decoys": g.decoys,
    }
    truth_path.parent.mkdir(parents=True, exist_ok=True)
    truth_path.write_text(json.dumps(truth, indent=1) + "\n", encoding="utf-8")

    def rel(p: Path) -> str:
        p = p.resolve()
        return p.relative_to(ROOT).as_posix() if p.is_relative_to(ROOT) else p.as_posix()

    st = defaultdict(int)
    for e in g.truth.values():
        st[e["expected_status"]] += 1
    print(f"seed {args.seed} -> {rel(out)}: {len(g.stock)} stock, {len(g.transfers)} transfers, "
          f"{len(g.sales)} sales, {len(g.deliveries)} deliveries")
    print(f"truth -> {rel(truth_path)}: {len(g.truth)} exposures {dict(st)}, "
          f"{len(g.decoys)} decoy records, {len(g.unassigned)} unassigned")
    return 0


if __name__ == "__main__":
    sys.exit(main())
